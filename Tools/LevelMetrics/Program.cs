// LEVEL METRICS, command line: the movement values are read from Assets/Config/MovementConfig.asset (the live,
// inspector-tuned numbers; a field the asset does not list keeps the code's default), the physics tick from
// ProjectSettings/TimeManager.asset, and LevelMetricsMath (the game's own file) makes the report.
//   cd Tools/LevelMetrics && dotnet run
//   dotnet run -- <path.md>      also writes the report to that file
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

static class Program
{
    static int Main(string[] args)
    {
        Console.OutputEncoding = Encoding.UTF8;
        string project = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", ".."));
        string asset = Path.Combine(project, "Assets", "Config", "MovementConfig.asset");
        if (!File.Exists(asset)) { Console.WriteLine("no MovementConfig.asset at " + asset); return 1; }

        var found = new Dictionary<string, float>();
        foreach (string line in File.ReadAllLines(asset))
        {
            var m = Regex.Match(line, @"^  (\w+): (-?[0-9.]+)$");
            if (m.Success && float.TryParse(m.Groups[2].Value, NumberStyles.Float, CultureInfo.InvariantCulture, out float f)) found[m.Groups[1].Value] = f;
        }
        var v = new LevelMetricsMath.Values();
        int read = 0;
        foreach (var f in typeof(LevelMetricsMath.Values).GetFields(BindingFlags.Public | BindingFlags.Instance))
        {
            if (!found.TryGetValue(f.Name, out float x)) continue;
            if (f.FieldType == typeof(int)) f.SetValue(v, (int)x); else f.SetValue(v, x);
            read++;
        }
        string tm = Path.Combine(project, "ProjectSettings", "TimeManager.asset");
        if (File.Exists(tm))
        {
            var fm = Regex.Match(File.ReadAllText(tm), @"Fixed Timestep: ([0-9.]+)");
            if (fm.Success) v.fixedDeltaTime = float.Parse(fm.Groups[1].Value, CultureInfo.InvariantCulture);
        }
        string report = LevelMetricsMath.Report(v, new[] { 8f, 10f, 12f, 14f, 16f, 18f, 20f, 24f }, new[] { 10f, 17f, 28f, 35f, 45f }, new[] { 2f, 3.9f, 6f, 9f, 12f, 20f });
        Console.WriteLine("(" + read + " values read from MovementConfig.asset, the rest the code's defaults)");
        Console.WriteLine(report);
        if (args.Length > 0)
        {
            string path = Path.GetFullPath(args[0]);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, "# Level metrics\n\nGenerated by Tools/LevelMetrics from Assets/Config/MovementConfig.asset. Do not edit: regenerate.\n\n" + report);
            Console.WriteLine("(written to " + path + ")");
        }
        return 0;
    }
}
