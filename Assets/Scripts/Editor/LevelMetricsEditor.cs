using System.IO;
using UnityEditor;
using UnityEngine;

/// <summary>
/// The LevelMetrics asset's inspector and its menu: Momentum/Level Metrics/Create Or Refresh makes
/// Assets/Config/LevelMetrics.asset (pointing at Assets/Config/MovementConfig.asset), regenerates the report, prints
/// it to the console and writes Docs/Design/level-metrics.md. The asset is also made on its own the first time the
/// editor loads these scripts, so there is nothing to click. The inspector shows the report in a monospace box
/// with the same three buttons.
/// </summary>
[CustomEditor(typeof(LevelMetrics))]
public class LevelMetricsEditor : Editor
{
    const string AssetPath = "Assets/Config/LevelMetrics.asset";
    const string ConfigPath = "Assets/Config/MovementConfig.asset";
    const string DocPath = "Docs/Design/level-metrics.md";
    static GUIStyle mono;

    public override void OnInspectorGUI()
    {
        var m = (LevelMetrics)target;
        serializedObject.Update();
        EditorGUILayout.PropertyField(serializedObject.FindProperty("config"));
        EditorGUILayout.PropertyField(serializedObject.FindProperty("entrySpeeds"), true);
        EditorGUILayout.PropertyField(serializedObject.FindProperty("slopeAngles"), true);
        EditorGUILayout.PropertyField(serializedObject.FindProperty("dropHeights"), true);
        serializedObject.ApplyModifiedProperties();
        GUILayout.Space(6);
        using (new EditorGUILayout.HorizontalScope())
        {
            if (GUILayout.Button("Recalculate")) { m.Recalculate(); EditorUtility.SetDirty(m); }
            if (GUILayout.Button("Print to Console")) Debug.Log(m.report);
            if (GUILayout.Button("Write " + DocPath)) WriteDoc(m);
        }
        GUILayout.Space(6);
        if (mono == null) mono = new GUIStyle(EditorStyles.textArea) { font = Font.CreateDynamicFontFromOSFont("Consolas", 11), wordWrap = false, richText = false };
        EditorGUILayout.LabelField("The report (read only; the numbers come from the movement config)", EditorStyles.boldLabel);
        EditorGUILayout.TextArea(m.report ?? "", mono, GUILayout.MinHeight(400f), GUILayout.ExpandHeight(true));
    }

    static string ProjectRoot => Directory.GetParent(Application.dataPath).FullName;

    public static void WriteDoc(LevelMetrics m)
    {
        string path = Path.Combine(ProjectRoot, DocPath);
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        File.WriteAllText(path, "# Level metrics\n\nGenerated by LevelMetrics (Momentum/Level Metrics/Create Or Refresh) from " + ConfigPath + ". Do not edit: regenerate.\n\n" + m.report);
        Debug.Log("LevelMetrics: wrote " + DocPath);
    }

    [MenuItem("Momentum/Level Metrics/Create Or Refresh")]
    public static void CreateOrRefresh()
    {
        var m = AssetDatabase.LoadAssetAtPath<LevelMetrics>(AssetPath);
        if (m == null)
        {
            m = ScriptableObject.CreateInstance<LevelMetrics>();
            AssetDatabase.CreateAsset(m, AssetPath);
        }
        if (m.config == null) m.config = AssetDatabase.LoadAssetAtPath<MovementConfig>(ConfigPath);
        m.Recalculate();
        EditorUtility.SetDirty(m);
        AssetDatabase.SaveAssets();
        WriteDoc(m);
        Debug.Log("LevelMetrics:\n" + m.report);
        Selection.activeObject = m;
    }

    /// The asset exists without anyone clicking: made once the scripts load, when the config folder is there
    [InitializeOnLoadMethod]
    static void EnsureAsset()
    {
        EditorApplication.delayCall += () =>
        {
            if (!AssetDatabase.IsValidFolder("Assets/Config")) return;
            if (AssetDatabase.LoadAssetAtPath<LevelMetrics>(AssetPath) != null) return;
            CreateOrRefresh();
        };
    }
}
